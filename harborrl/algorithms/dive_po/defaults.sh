#!/usr/bin/env bash
# DIVE-PO environment defaults for Qwen3-8B.
# Mixed-data DAPO exploration wrapper without dynamic sampling.
#
# Defaults use the 2026-06-05 mixed DAPO Agent57/NGU-lite run as the base and
# enable the robust exploration fixes: length-invariant episodic novelty,
# coarse lifelong keys, soft trust gate, and dual-stream intrinsic advantage.
# Override env vars explicitly for ablations or to reproduce the original run.
# Dataset and algorithm selection intentionally follow the mixed nodynamic base script:
#   DATASET=seta|safety|agentharm|mixed
#   ALGO=grpo|dapo
#
# USAGE:
#   bash examples/training/train_qwen3_8b_seta_dive_po.sh
#   DATASET=safety ALGO=dapo bash examples/training/train_qwen3_8b_seta_dive_po.sh                   # ASB + DAPO override
#   EXPLORATION_PROFILE=robust_dapo_lite bash examples/training/train_qwen3_8b_seta_dive_po.sh       # conservative DAPO exploration override
#   EXPLORATION_PROFILE=off EXPLORE_AGENT57_LITE=0 bash examples/training/train_qwen3_8b_seta_dive_po.sh # baseline-style ablation
#   EXPLORE_ENTROPY_COEF=0.01 bash examples/training/train_qwen3_8b_seta_dive_po.sh                  # +entropy bonus
#   EXPLORE_THINK_MODE=1 bash examples/training/train_qwen3_8b_seta_dive_po.sh                        # +think mode
#   EXPLORE_INTRINSIC=1 bash examples/training/train_qwen3_8b_seta_dive_po.sh                         # +intrinsic reward
#   EXPLORE_SAFETY_FILTER=1 bash examples/training/train_qwen3_8b_seta_dive_po.sh                     # +safety filter
#   ALGO=dapo EXPLORE_CDE_ACTOR=1 bash examples/training/train_qwen3_8b_seta_dive_po.sh               # +CDE actor/PPL bonus
#   EXPLORE_ENTROPY_COEF=0.01 EXPLORE_INTRINSIC=1 bash examples/training/train_qwen3_8b_seta_dive_po.sh # combined
#
# BASELINE OPTIONS:
#   DATASET                  : seta|safety|agentharm|mixed (default mixed)
#   ALGO                     : grpo|dapo (default dapo)
#   MIX_SETA_RATIO           : mixed seta ratio
#   MIX_SAFETY_RATIO         : mixed Agent-SafetyBench ratio
#   MIX_AGENTHARM_RATIO      : mixed AgentHarm ratio
#   SETA_SAFETY              : none (default none)
#   SAFETY_BENCH_REWARD      : rule|dense_rule (default dense_rule)
#   AGENTHARM_REWARD         : rule|dense_rule (default dense_rule)
#   TERMINAL_STRUCTURED_METRICS: Emit per-dataset JSON reward breakdowns (default 1)
#   TERMINAL_METRICS_JSONL   : Override JSONL path (default <run_dir>/logs/metrics.jsonl)
#   TERMINAL_WANDB_METRIC_PROFILE: compact|full (default compact)
#
# EXPLORATION OPTIONS:
#   EXPLORATION_PROFILE      : off|robust_dapo_lite|spear_lite (default spear_lite)
#   EXPLORE_ENTROPY_COEF      : Entropy bonus coefficient (default 0.0 = OFF)
#                               Recommended: 0.005 ~ 0.02 (AEPO-style)
#   EXPLORE_THINK_MODE        : Enable Qwen3 think mode (default 1)
#   EXPLORE_TEMP_HIGH         : Rollout temperature override (empty = inherit baseline 1.0)
#   EXPLORE_INTRINSIC         : Count-based intrinsic reward (default 1)
#   EXPLORE_INTRINSIC_COEF    : Intrinsic reward weight (default 0.015)
#   EXPLORE_INTRINSIC_SCHEDULE: constant|cosine|linear (default cosine)
#   EXPLORE_INTRINSIC_DECAY_STEPS: Schedule length in train steps (default 120)
#   EXPLORE_INTRINSIC_GRANULARITY: raw|signature (default signature)
#   EXPLORE_INTRINSIC_SCOPE   : process|episode (default episode)
#   EXPLORE_SAFETY_FILTER     : Regex-based dangerous command penalty (0=OFF, 1=ON)
#   EXPLORE_SAFETY_FILTER_COEF: Safety penalty coefficient (default -0.5)
#   EXPLORE_MAX_TURN          : Override MAX_TURN (empty = inherit baseline 10)
#
# LaMer-inspired Options (from ICLR '26 "Meta-RL Induces Exploration in Language Agents"):
#   EXPLORE_LPRND             : LP-RND lifelong novelty bonus (0=OFF, 1=ON)
#                               Uses mean negative policy logprob as zero-cost novelty
#                               signal; no extra model parameters.
#   EXPLORE_LPRND_COEF        : LP-RND reward weight (default 0.05)
#   EXPLORE_LPRND_SCHEDULE    : constant|cosine|linear (default constant)
#   EXPLORE_LPRND_DECAY_STEPS : Schedule length in train steps (0=OFF)
#   EXPLORE_LPRND_CLIP        : LP-RND z-score clip (default 3.0)
#   EXPLORE_LPRND_WARMUP      : Number of trajectories before LP-RND stats start (default 32)
#   EXPLORE_SCORE_BONUS_COMPONENTS: score-space exploration injection (default none)
#   EXPLORE_ADVANTAGE_BONUS   : Add intrinsic stream after GRPO normalization (default 1)
#   EXPLORE_ADVANTAGE_BONUS_MODE: component|dual_stream (default dual_stream)
#   EXPLORE_ADVANTAGE_LAMBDA  : Dual-stream intrinsic advantage coefficient (default 0.05)
#   EXPLORE_ADVANTAGE_LAMBDA_SCHEDULE: constant|linear|cosine (default constant)
#   EXPLORE_ADVANTAGE_LAMBDA_DECAY_STEPS: decay horizon for the dual stream (default 0)
#   EXPLORE_ADVANTAGE_BONUS_CLIP: absolute postnorm bonus clip (default 0.5)
#   EXPLORE_CDE_ACTOR         : CDE actor/PPL bonus (default 0)
#                               Adds omega * min(|r|/kappa, alpha * -mean_logprob)
#   EXPLORE_CDE_ACTOR_OMEGA   : CDE actor bonus weight (default 0.02)
#   EXPLORE_CDE_ACTOR_KAPPA   : Reward-magnitude clip divisor (default 4.0)
#   EXPLORE_CDE_ACTOR_ALPHA   : Log-PPL scale before clipping (default 0.05)
#   EXPLORE_CDE_ACTOR_REWARD_GATE: nonzero|positive|none (default positive)
#   EXPLORE_CDE_ACTOR_DECAY_STEPS: Linear omega decay steps (0=OFF)
#   EXPLORE_RETRY_ATTEMPTS    : Multi-attempt reflection (1=OFF/baseline, 2-3=ON)
#                               LaMer uses 3; each failed attempt generates a reflection turn
#   EXPLORE_RETRY_TRAJ_GAMMA  : Cross-attempt discount factor (default 1.0=OFF; LaMer uses 0.6)
#                               Rewards in earlier attempts are discounted, incentivising faster solve

